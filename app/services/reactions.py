"""Реакции на ответы ученика (ТЗ раздел 9 — пулы зафиксированы, не менять).

Реакция не должна повторяться два раза подряд: последняя показанная
хранится в users.last_reaction_id; функции исключают её из выбора.
Возвращают (id, текст): id — порядковый номер (1..10) в пуле.
"""
import random

# Позитивные (правильный ответ) — дословно из ТЗ раздел 9
POSITIVE_REACTIONS: list[str] = [
    "Вот это точно! Так держать",
    "Да! Именно так, без заминки",
    "Чисто. Прям как по конспекту",
    "Правильно! Мозг прокачался ещё на шаг",
    "Есть! Это был не самый лёгкий вопрос",
    "Красава! И это без репетитора",
    "Точно в цель. Ошибки у тебя не приживаются",
    "Лови +1 к уверенности перед экзаменом",
    "Правильно! Именно так и рассуждаешь на реальном ЦЭ",
    "Бум! Стрик в безопасности ✅",
]

# Мотивационные (неправильный ответ) — дословно из ТЗ раздел 9
MOTIVATIONAL_REACTIONS: list[str] = [
    "Бывает. Это не ошибка, это точка роста",
    "Ошибка — единственный способ запомнить навсегда",
    "Даже стобалльники начинали с ошибок",
    "Запиши тему в «повторить» — и она станет твоей",
    "Минус балл в тесте, плюс опыт. Следующий — твой",
    "Не совпало — теперь ты знаешь, что подтянуть",
    "Слабые места потому и слабые, что их можно прокачать",
    "Ты на шаг ближе к экзамену, чем вчера",
    "Даже неверный путь — путь. Разберём и пойдём дальше",
    "Это задание ты больше не пропустишь. Вперёд!",
]


def _pick(pool: list[str], last_id: int | None) -> tuple[int, str]:
    """Случайная реакция из пула, не совпадающая с last_id.

    Если у пользователя ещё нет последней реакции (None) — любой вариант.
    Пулы по 10 фраз, поэтому исключение одной не оставляет пустой выбор.
    """
    candidates = [
        (i + 1, text)
        for i, text in enumerate(pool)
        if last_id is None or i + 1 != last_id
    ]
    return random.choice(candidates)


def positive_reaction(last_id: int | None) -> tuple[int, str]:
    """Позитивная реакция на правильный ответ."""
    return _pick(POSITIVE_REACTIONS, last_id)


def motivational_reaction(last_id: int | None) -> tuple[int, str]:
    """Мотивационная реакция на неправильный ответ."""
    return _pick(MOTIVATIONAL_REACTIONS, last_id)